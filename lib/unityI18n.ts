export type PackageSlug =
  | "starter-website"
  | "business-website"
  | "business-web-admin"
  | "system-plus"
  | "web-app-custom"
  | "ai-development"
  | "enterprise-web-app";

export const packageSlugs: PackageSlug[] = [
  "starter-website",
  "business-website",
  "business-web-admin",
  "system-plus",
  "web-app-custom",
  "ai-development",
  "enterprise-web-app",
];

export function isPackageSlug(value: string): value is PackageSlug {
  return packageSlugs.includes(value as PackageSlug);
}

export function getSafeLang(value: string | null): Lang {
  if (
    value === "th" ||
    value === "en" ||
    value === "ja" ||
    value === "zh" ||
    value === "ko"
  ) {
    return value;
  }

  return "th";
}

